"""Restore CMDPC's original five-class label IDs: Drill_tail 3 -> 4.

Ordinary Python script, standard library only. Backs up labels/metadata/caches
before changing anything. Default root is the user's server dataset directory.
Run with --dry-run to inspect counts without writing files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import stat
import tempfile
import uuid
import zipfile
from datetime import datetime
from decimal import Decimal, InvalidOperation
from pathlib import Path


DEFAULT_ROOT = "/home/zhangyuhang/dataset/Coal_mine/CMDPC_yolo_obb"
NAMES = ["Drill_body", "Drill_head", "Drill_pipe", "Drill_pipec", "Drill_tail"]


def checked(path: Path, root: Path) -> Path:
    """Only write/delete resolved paths inside the explicitly selected dataset."""
    target = path.resolve()
    if not target.is_relative_to(root) or target == root:
        raise ValueError(f"Path escapes dataset root: {path}")
    if path.is_symlink():
        raise ValueError(f"Refusing to replace a symlink: {path}")
    return target


def convert_labels(raw: bytes, path: Path) -> tuple[bytes, list[int], list[int]]:
    """Replace only the first token on class-3 rows; preserve all coordinates/spacing."""
    bom = b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
    body = raw[len(bom):]
    before, after, output = [0] * 5, [0] * 5, []
    for number, line in enumerate(body.splitlines(keepends=True), 1):
        tokens = line.split()
        if not tokens:
            output.append(line)
            continue
        try:
            value = Decimal(tokens[0].decode("ascii"))
            if not value.is_finite() or value != value.to_integral_value() or not 0 <= value <= 4:
                raise ValueError("class ID must be an integer in 0..4")
            cls = int(value)
            if len(tokens) < 5 or len(tokens) % 2 == 0:
                raise ValueError("expected a YOLO box or polygon row")
            if not all(math.isfinite(float(x)) for x in tokens[1:]):
                raise ValueError("non-finite coordinates")
        except (InvalidOperation, ValueError, UnicodeDecodeError) as exc:
            raise ValueError(f"Invalid annotation at {path}:{number}: {exc}") from exc
        before[cls] += 1
        after[4 if cls == 3 else cls] += 1
        if cls == 3:
            match = re.match(rb"^(\s*)\S+", line)
            line = match.group(1) + b"4" + line[match.end():]
        output.append(line)
    return bom + b"".join(output), before, after


def atomic_write(path: Path, content: bytes, mode: int) -> None:
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".cmdpc_restore_", delete=False) as f:
            temporary = Path(f.name)
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def dataset_yaml(root: Path, splits: list[str]) -> bytes:
    # JSON string quoting is also valid YAML and handles spaces/non-ASCII paths.
    lines = ["# CMDPC restored training class IDs; generated by restore_cmdpc_label_ids.py",
             "path: " + json.dumps(root.as_posix(), ensure_ascii=False)]
    lines += [f"{split}: images/{split}" for split in splits]
    lines += ["", "nc: 5", "names:"]
    lines += [f"  {i}: {name}" for i, name in enumerate(NAMES)]
    return ("\n".join(lines) + "\n").encode("utf-8")


def restore(root: Path, dry_run: bool = False) -> None:
    root = root.expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError(f"Not a dataset directory: {root}")
    splits = [s for s in ("train", "val", "test") if (root / "labels" / s).is_dir()]
    if not {"train", "val"}.issubset(splits):
        raise ValueError(f"Expected labels/train and labels/val under {root}")
    for split in splits:
        if not (root / "images" / split).is_dir():
            raise ValueError(f"Missing corresponding image directory: {root / 'images' / split}")

    originals, modes, planned, stats = {}, {}, {}, {}
    for split in splits:
        paths = sorted((root / "labels" / split).rglob("*.txt"))
        if not paths:
            raise ValueError(f"No .txt annotation files in labels/{split}")
        before, after, changed = [0] * 5, [0] * 5, 0
        for candidate in paths:
            path = checked(candidate, root)
            if path in originals:
                raise ValueError(f"Duplicate resolved label path: {path}")
            raw = path.read_bytes()
            converted, counts_before, counts_after = convert_labels(raw, path)
            originals[path] = raw
            modes[path] = stat.S_IMODE(path.stat().st_mode)
            before = [a + b for a, b in zip(before, counts_before)]
            after = [a + b for a, b in zip(after, counts_after)]
            if converted != raw:
                planned[path] = converted
                changed += 1
        stats[split] = {"files": len(paths), "changed_files": changed, "before": before, "after": after}

    metadata = {checked(root / "data.yaml", root): dataset_yaml(root, splits)}
    # Keep an existing class-name list consistent; do not create one unnecessarily.
    if (root / "classes.txt").exists():
        metadata[checked(root / "classes.txt", root)] = ("\n".join(NAMES) + "\n").encode("utf-8")
    for path, content in metadata.items():
        originals[path] = path.read_bytes() if path.exists() else None
        modes[path] = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o644
        if originals[path] != content:
            planned[path] = content
    caches = set()
    for pattern in ("*.cache", "*.cache.npy"):
        caches.update(checked(p, root) for p in (root / "labels").rglob(pattern) if p.is_file())
        caches.update(checked(p, root) for p in root.glob(pattern) if p.is_file())
    for path in sorted(caches):
        originals[path] = path.read_bytes()
        modes[path] = stat.S_IMODE(path.stat().st_mode)

    print("CMDPC LABEL RESTORE | Drill_tail: 3 -> 4", flush=True)
    print(f"Dataset: {root}", flush=True)
    print("Counts follow IDs [0, 1, 2, 3, 4]; ID 3 will be empty.", flush=True)
    for split, counts in stats.items():
        print(f"  {split}: files={counts['files']} | changed_files={counts['changed_files']} | "
              f"{counts['before']} -> {counts['after']}", flush=True)
    print(f"Metadata updates: {sum(p in planned for p in metadata)} | stale caches: {len(caches)}", flush=True)
    if dry_run:
        print("DRY RUN: no files written or deleted.", flush=True)
        return
    if not planned and not caches:
        print("Already restored. No changes needed.", flush=True)
        return

    # Complete the backup before any label/metadata/cache mutation.
    backup = root.parent / (root.name + "_labels_backup_" + datetime.now().strftime("%Y%m%d_%H%M%S")
                            + "_" + uuid.uuid4().hex[:8] + ".zip")
    manifest = {"dataset_root": str(root), "operation": "class 3 -> 4", "splits": stats,
                "files": {str(p.relative_to(root)): {
                    "sha256": hashlib.sha256(raw).hexdigest() if raw is not None else None,
                    "existed": raw is not None, "mode": modes[p]} for p, raw in originals.items()}}
    with zipfile.ZipFile(backup, "x", compression=zipfile.ZIP_DEFLATED) as archive:
        for path, raw in originals.items():
            if raw is not None:
                archive.writestr(path.relative_to(root).as_posix(), raw)
        archive.writestr("_cmdpc_restore_manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    with zipfile.ZipFile(backup) as archive:
        failed = archive.testzip()
        if failed:
            raise OSError(f"Backup integrity check failed: {backup}: {failed}")
    print(f"Backup: {backup}", flush=True)

    attempted = []
    try:
        # Detect modifications made since preflight before changing the dataset.
        for path, raw in originals.items():
            current = path.read_bytes() if path.exists() else None
            if current != raw:
                raise RuntimeError(f"File changed during preflight; stop other dataset writers: {path}")
        for path, content in planned.items():
            checked(path, root)
            attempted.append(path)
            atomic_write(path, content, modes[path])
        for path in sorted(caches):
            checked(path, root)
            attempted.append(path)
            path.unlink()
        for path, raw in originals.items():
            if path in caches:
                if path.exists():
                    raise RuntimeError(f"Cache was recreated during conversion: {path}")
            elif path.read_bytes() != planned.get(path, raw):
                raise RuntimeError(f"Post-write verification failed: {path}")
    except BaseException:
        errors = []
        for path in reversed(attempted):
            try:
                checked(path, root)
                if originals[path] is None:
                    path.unlink(missing_ok=True)
                else:
                    atomic_write(path, originals[path], modes[path])
            except Exception as exc:
                errors.append(f"{path}: {exc}")
        print(f"Restore failed. Original files {'restored' if not errors else 'need recovery from ZIP'}; backup: {backup}", flush=True)
        for error in errors:
            print("  Rollback error: " + error, flush=True)
        raise
    print("SUCCESS: all label bytes verified; only class-3 IDs changed to 4.", flush=True)
    print(f"Dataset YAML: {root / 'data.yaml'}", flush=True)
    print("Use Slot-YOLO/datasets_config/CMDPC.yaml (five classes), without the old 3->4 evaluation mapping.", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(DEFAULT_ROOT), help="CMDPC dataset root")
    parser.add_argument("--dry-run", action="store_true", help="Print counts; do not modify files")
    args = parser.parse_args()
    restore(args.root, args.dry_run)


if __name__ == "__main__":
    main()
